#!/usr/bin/env python3
"""Build native Flare data for the compact surface; no runtime Python needed.

Angband's gen-cave.c inspired the lots, clear streets and northern entrance.
The implementation and map data here are original Diantre work.
"""
from pathlib import Path
import hashlib
import json
import random

ROOT = Path(__file__).resolve().parents[1] / "diantre"
LAYERS = ("background_base", "background", "object", "mountain_top", "collision")
WIDTH, HEIGHT = 44, 44
CHUNK_W, CHUNK_H = 18, 18
ENTRANCE = (18, 8)
STREET_Y = 16
GROUPS = {
    "start": ("florin", "udana"),
    "normal_a": ("yora", "abasi"),
    "normal_b": ("martigan", "bakat"),
    "end": ("loren",),
}
NAMES = {
    "florin": "Florin, Apothecary", "udana": "Udana, Metalworker",
    "yora": "Yora, Enchanter", "abasi": "Abasi, Traveling Merchant",
    "martigan": "Martigan", "bakat": "Bakat, Goblin Packrat",
    "loren": "Loren, Undead Trader",
}


class Map:
    def __init__(self, width, height, seed):
        self.w, self.h = width, height
        self.rng = random.Random(seed)
        self.layers = {name: [[0] * width for _ in range(height)] for name in LAYERS}
        self.objects = []
        for y in range(height):
            for x in range(width):
                self.set("background_base", x, y, self.rng.randrange(16, 32))

    def set(self, layer, x, y, tile):
        if not (0 <= x < self.w and 0 <= y < self.h):
            raise ValueError((layer, x, y, tile))
        self.layers[layer][y][x] = tile

    def path(self, a, b):
        x, y = a
        while True:
            self.set("background", x, y, self.rng.randrange(40, 48))
            if (x, y) == b:
                return
            if x != b[0]:
                x += 1 if b[0] > x else -1
            else:
                y += 1 if b[1] > y else -1

    def cabin(self, merchant, x, y, length):
        """Same native log-cabin assembly used in Black Oak City, not ruins."""
        self.set("object", x - 1, y, 208)
        self.set("object", x, y, 209)
        for cy in range(y - length + 2, y):
            self.set("object", x, cy, 210)
        self.set("object", x, y - length + 1, 211)
        for cy in range(y - length + 1, y + 1):
            for cx in (x - 1, x):
                self.set("collision", cx, cy, 1)
        npc_x, npc_y = x, y + 2
        # Southern shops connect around their footprint, never through a wall.
        if y > STREET_Y:
            self.path((npc_x, npc_y), (x + 2, npc_y))
            self.path((x + 2, npc_y), (x + 2, STREET_Y))
        else:
            self.path((npc_x, npc_y), (npc_x, STREET_Y))
        self.set("object", x + 1, y + 1, 138)
        self.set("collision", x + 1, y + 1, 1)
        self.objects.append(
            f"[npc]\ntype=npc\nlocation={npc_x},{npc_y},1,1\n"
            f"direction=5\nfilename=npcs/town/{merchant}.txt\n"
        )
        self.objects.append(
            f"[event]\ntype=event\nlocation={x + 1},{y + 1},1,1\n"
            f"hotspot=location\ntooltip={NAMES[merchant]}\n"
        )

    def write(self, filename, header):
        lines = ["# Generated by tools/build_surface.py; edit the generator.", "[header]",
                 f"width={self.w}", f"height={self.h}", "tilewidth=192", "tileheight=96",
                 "orientation=isometric", "tileset=tilesetdefs/town/compact_palette.txt", header]
        for name in LAYERS:
            lines.extend(("\n[layer]", f"type={name}", "data="))
            lines.extend(",".join(map(str, row)) for row in self.layers[name])
        lines.extend("\n" + s for s in self.objects)
        p = ROOT / filename
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("\n".join(lines).rstrip() + "\n")


def build_chunks():
    # Remove only this generator's obsolete rectangular prototype modules.
    for variant in range(4):
        obsolete = ROOT / f"maps/town/compact/normal_{variant}.txt"
        if obsolete.exists():
            obsolete.unlink()
    for kind, merchants in GROUPS.items():
        for variant in range(4):
            m = Map(CHUNK_W, CHUNK_H, 3100 + variant)
            m.path((0, STREET_Y), (CHUNK_W - 1, STREET_Y))
            m.path((0, STREET_Y + 1), (CHUNK_W - 1, STREET_Y + 1))
            m.path((9, 0), (9, CHUNK_H - 1))
            positions = [(5 + variant % 2, 12), (13 + variant % 2, 13)]
            # Groves occupy spare lots rather than leaving a blank central field.
            for tx, ty in ((4, 3), (13, 3), (3, 6), (14, 6)):
                m.set("object", tx, ty, m.rng.choice((248, 249, 252, 253)))
                m.set("collision", tx, ty, 1)
            order = list(merchants)
            if variant >= 2:
                order.reverse()
            for i, (merchant, (x, y)) in enumerate(zip(order, positions)):
                m.cabin(merchant, x, y, 3 + (variant + i) % 2)
            unique = f"\nprocgen_unique_status=diantre_compact_{kind}" if kind.startswith("normal") else ""
            m.write(f"maps/town/compact/{kind}_{variant}.txt",
                    f"hero_pos=9,{STREET_Y}\nprocgen_type={kind.split('_')[0]}{unique}")

    links = Map(CHUNK_W, CHUNK_H, 0)
    # Only a blocked corner is copied by links: the actual streets already join.
    for side in ("north", "south", "west", "east"):
        links.objects.append(f"[event]\ntype=event\nlocation=0,0,1,1\nprocgen_link={side}\n")
    links.write("maps/town/compact/links.txt", "hero_pos=9,16\nprocgen_type=links")


def clearing(x, y):
    # Broad enough for every lot variant; rounded, irregular woodland perimeter.
    left = 3 + (1 if y < 13 or y > 34 else 0)
    right = 34 - (1 if y < 12 or y > 34 else 0)
    return left <= x <= right and 9 <= y <= 36


def build_town():
    m = Map(WIDTH, HEIGHT, 413)
    modifications = []

    def overlay(layer, x, y, tile):
        m.set(layer, x, y, tile)
        modifications.append(f"mapmod={layer},{x},{y},{tile}")

    for y in range(HEIGHT):
        for x in range(WIDTH):
            if clearing(x, y):
                continue
            overlay("collision", x, y, 1)
            if y < 9 and 2 <= x <= 35:
                # One coherent rock plateau, inaccessible behind its north face.
                if y <= 8:
                    overlay("mountain_top", x, y, 27032 + m.rng.randrange(16))
                    overlay("object", x, y, 0)
                continue
            # A deep visible woodland belt extends beyond the playable clearing.
            inner_edge = clearing(x + 1, y) or clearing(x - 1, y) or clearing(x, y - 1)
            if inner_edge or (x % 2 == 0 and y % 2 == (x // 2) % 2):
                tree = m.rng.choice((248, 249, 250, 251, 252, 253, 254, 255))
                overlay("object", x, y, tree)

    # Rock facade runs into the woodland on both sides; no passage behind it.
    for x in range(2, 36):
        overlay("object", x, 8, 49 if x % 2 else 53)
    # Native mine opening, set into that same single rock face.
    overlay("object", ENTRANCE[0], ENTRANCE[1], 228)
    for y in range(9, 36):
        for x in range(17, 20):
            overlay("background", x, y, 40 + (x + y) % 8)
    for y in (17, 18):
        for x in range(4, 34):
            overlay("background", x, y, 40 + (x + y) % 8)
    overlay("object", 20, 20, 76)
    overlay("collision", 20, 20, 1)

    m.objects.append(
        "[event]\ntype=event\nlocation=0,0,36,36\n"
        "procgen_filename=maps/town/compact/rules.txt\n"
    )
    # Flare copies chunks from (0,0), then applies on_load events. Reapply only
    # the perimeter, plateau and main access, preserving each generated lot.
    m.objects.append("[event]\ntype=event\nlocation=0,0,1,1\nactivate=on_load\n"
                     + "\n".join(modifications) + "\n")
    m.objects.append(
        "[event]\ntype=event\nlocation=0,0,1,1\nactivate=on_load\n"
        "set_status=diantre_town_hamlet_forest\n"
        "unset_status=diantre_town_forest,diantre_town_woodland,diantre_town_rocky,"
        "diantre_town_swamp,diantre_town_meadow,diantre_town_coast,diantre_town_snow,"
        "diantre_town_cave,diantre_town_ruins,diantre_town_citadel\n"
    )
    m.objects.extend((
        "[event]\ntype=event\nlocation=18,9,1,1\nhotspot=location\n"
        "tooltip=Dungeon Entrance\nscript=scripts/town/enter_dungeon.txt\n",
        "[event]\ntype=event\nlocation=18,10,1,1\nactivate=on_trigger\nintermap_id=dungeon_exit\n",
        "[event]\ntype=event\nlocation=20,20,1,1\nhotspot=location\n"
        "stash=true\ntooltip=Shared Stash\nsoundfx=soundfx/wood_open.ogg\n",
    ))
    m.write("maps/town/hamlet_forest.txt",
            "hero_pos=18,10\ntitle=Woodland Hamlet\nmusic=music/town_theme.ogg\nfogofwar=0")


def build_palette():
    lines = ["# Native Empyrean graphics, with a single raised, inaccessible rock cap.",
             "INCLUDE tilesetdefs/tileset_grassland.txt", "", "[tileset]",
             "img=images/tilesets/tileset_cave.png"]
    for line in (ROOT / "tilesetdefs/tileset_cave.txt").read_text().splitlines():
        if line.startswith("tile="):
            tid, x, y, w, h, ox, oy = map(int, line[5:].split(","))
            if 16 <= tid <= 31:
                lines.append(f"tile={27016 + tid},{x},{y},{w},{h},{ox},{oy + 244}")
    (ROOT / "tilesetdefs/town/compact_palette.txt").write_text("\n".join(lines) + "\n")


def main():
    build_palette()
    build_chunks()
    build_town()
    rules = ["[settings]", "doors_max=0", "main_path_length_min=4",
             "main_path_length_max=4", "main_path_attempts_max=1000",
             "branch_length_min=0", "branch_length_max=0", "branches_per_door_level_max=0",
             "", "[chunks]", "filename=maps/town/compact/links.txt"]
    for kind in GROUPS:
        rules.extend(f"filename=maps/town/compact/{kind}_{i}.txt" for i in range(4))
    (ROOT / "maps/town/compact/rules.txt").write_text("\n".join(rules) + "\n")
    update_manifest()


def update_manifest():
    path = ROOT / "ASSET_MANIFEST.json"
    manifest = json.loads(path.read_text())
    for variant in range(4):
        manifest["files"].pop(f"maps/town/compact/normal_{variant}.txt", None)
    paths = [ROOT / "maps/town/hamlet_forest.txt", ROOT / "maps/town/biomes.txt",
             ROOT / "scripts/town/return.txt", ROOT / "settings.txt",
             ROOT / "tilesetdefs/town/compact_palette.txt",
             *sorted((ROOT / "maps/town/compact").glob("*.txt"))]
    note = "Diantre 0.5.0: compact outdoor surface inspired by Angband; original map data."
    for file in paths:
        key = file.relative_to(ROOT).as_posix()
        record = manifest["files"].get(key, {"sources": [], "changes": []})
        data = file.read_bytes()
        record.update(sha256=hashlib.sha256(data).hexdigest(), bytes=len(data))
        if note not in record["changes"]:
            record["changes"].append(note)
        manifest["files"][key] = record
    path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
